<?php

namespace Oatmael\WasmPhp\Instruction\Simd;

use Oatmael\WasmPhp\Execution\Store;
use Oatmael\WasmPhp\Instruction\InstructionInterface;
use Oatmael\WasmPhp\Type\V128;
use Oatmael\WasmPhp\Util\Floats;
use Oatmael\WasmPhp\Util\Shape;

class F64x2Nearest implements InstructionInterface {
    public static function fromInput(string $input, int &$offset): InstructionInterface {
        return new self();
    }

    public function execute(array &$stack, array &$call_stack, Store $store) {
        $stack[] = V128::fromLanes(Shape::F64x2, array_map(static fn ($a) => Floats::nearest($a), array_pop($stack)->lanes(Shape::F64x2)));
    }
}
